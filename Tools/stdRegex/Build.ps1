param(
    [string]$UpstreamRoot,
    [string]$OutputPath = (Join-Path $PSScriptRoot '../../src/stdRegex.cls')
)
$ErrorActionPreference = 'Stop'
$revision = '1619cd75526903045b8c5cb8c6048f93bc4160be'
if (-not $UpstreamRoot) {
    $UpstreamRoot = Join-Path ([IO.Path]::GetTempPath()) ('stdRegex-' + $revision)
    $files = @(
        'LICENSE', 'aio/make_aio.ps1', 'aio/HeaderComment.bas',
        'stdvba_regex3/make_stdregex3_aio.ps1', 'stdvba_regex3/HeaderCommentStdRegex3Standalone.bas',
        'stdvba_regex3/stdRegex3.cls', 'src/StaticStringBuilder.bas', 'src/ArrayBuffer.bas',
        'src/RegexNumericConstants.bas', 'src/RegexErrors.bas', 'src/RegexBytecode.bas',
        'src/RegexAst.bas', 'src/RegexUnicodeSupport.bas', 'src/RegexRanges.bas',
        'src/RegexIdentifierSupport.bas', 'src/RegexLexer.bas', 'src/RegexCompiler.bas',
        'src/RegexDfsMatcher.bas', 'src/RegexReplace.bas', 'src/StaticRegex.bas'
    )
    foreach ($file in $files) {
        $target = Join-Path $UpstreamRoot $file
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
        Invoke-WebRequest -Uri "https://raw.githubusercontent.com/sihlfall/vba-regex/$revision/$file" -OutFile $target
    }
}
Push-Location (Join-Path $UpstreamRoot 'stdvba_regex3')
try {
    & ./make_stdregex3_aio.ps1
    $engine = [IO.File]::ReadAllText((Join-Path (Get-Location) 'build/stdRegex3Standalone.cls')).Replace("`r`n", "`n")
} finally { Pop-Location }

# Keep the bundled engine and its singleton initialization, replacing the upstream wrapper.
$engine = $engine.Substring(0, $engine.IndexOf('Friend Sub protInit('))
$engine = $engine.Replace('stdRegex3', 'stdRegex')
$engine = [regex]::Replace($engine, '(?s)Private Const REGEX3_DEFAULT_STEPS_LIMIT.*?Private This As TThis\s*', '')
$engine = $engine.Replace('Error.Raise "Method called on object, not on class"', 'Err.Raise 1, "stdRegex", "Method called on object, not on class"')
# Exhausting a match budget must raise instead of silently returning a false negative.
$engine = $engine.Replace('protStaticRegexMatchNext(matcherState, regex, haystack)', 'protStaticRegexMatchNext(matcherState, regex, haystack, raiseOnLimit:=True)')
$engine = $engine.Replace('Err.Raise REGEX_ERR_STEP_LIMIT', 'Err.Raise REGEX_ERR_STEP_LIMIT, "stdRegex", "Regex processing step limit exceeded"')
$engine = $engine.Replace("        InitializeAstTable This.regex.bytecode`n    End If", "        InitializeAstTable This.regex.bytecode`n    Else`n        This.regex.stepsLimit = 10000`n    End If")

$wrapper = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'Wrapper.cls')).Replace("`r`n", "`n")
$headerEnd = $wrapper.IndexOf("'@module")
$header = $wrapper.Substring(0, $headerEnd)
$wrapper = $wrapper.Substring($headerEnd)
$wrapperProcStart = $wrapper.IndexOf("'Creates a regex object")
$declarations = $wrapper.Substring(0, $wrapperProcStart)
$procedures = $wrapper.Substring($wrapperProcStart)
$engine = $engine.Substring($engine.IndexOf('Private Enum StaticStringBuilderConstant'))
$engineProcStart = $engine.IndexOf('Private Sub AppendStr(')
$license = [IO.File]::ReadAllText((Join-Path $UpstreamRoot 'LICENSE')).Trim()
$licenseComment = (($license -split '\r?\n') | ForEach-Object { "' " + $_ }) -join "`n"
$output = $header + "Option Explicit`n`n' Bundled sihlfall/vba-regex $revision`n' Generated by Tools/stdRegex/Build.ps1. Edit Wrapper.cls and rebuild.`n" + $licenseComment + "`n`n" +
    $engine.Substring(0, $engineProcStart) + $declarations + $procedures + "`n" + $engine.Substring($engineProcStart)
$output = (($output -split "`n" | ForEach-Object { $_.TrimEnd() }) -join "`n").TrimEnd() + "`n"
[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutputPath), $output.Replace("`n", "`r`n"), [Text.UTF8Encoding]::new($false))
